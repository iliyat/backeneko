import type { GraphQLSchema } from "graphql";
import { renderSchemaNamespace } from "../schema/ts-types.ts";

export const TYPES_FILE = "types.d.ts";

// A .d.ts without top-level import/export is a script, so `declare namespace`
// is global: workspace files use these types without importing anything.
const PROXY = `  namespace Proxy {
    type Variables = Record<string, any> | null;

    interface Payload<TVariables = Variables> {
      query: string;
      variables?: TVariables;
      operationName?: string | null;
    }
  }`;

const INTERCEPT = `  namespace Intercept {
    type Route = "local" | "remote" | "split";
    type Mode = "auto" | "proxy" | "local";
    type OperationType = "query" | "mutation" | "subscription";
    type Data = Record<string, any> | null;

    interface Error {
      message: string;
      path?: readonly (string | number)[];
      locations?: ReadonlyArray<{ line: number; column: number }>;
      extensions?: Record<string, any>;
    }

    interface Result<TData = Data> {
      data?: TData;
      errors?: readonly Error[];
      extensions?: Record<string, any>;
    }

    interface Context<TVariables = Proxy.Variables> {
      operationName: string | null;
      operationType: OperationType;
      rootFields: string[];
      route: Route;
      target: string | null;
      query: string;
      variables: TVariables;
      rootField?: string;
      file: string;
    }

    type Before<TVariables = Proxy.Variables> = (
      payload: Proxy.Payload<TVariables>,
      ctx: Context<TVariables>,
    ) => Proxy.Payload<TVariables> | Promise<Proxy.Payload<TVariables>>;

    type After<TData = Data, TVariables = Proxy.Variables> = (
      result: Result<TData>,
      ctx: Context<TVariables>,
    ) => Result<TData> | Promise<Result<TData>>;

    type Match<TVariables = Proxy.Variables> = (ctx: Context<TVariables>) => boolean;
  }`;

export function typeDeclarations(schema: GraphQLSchema | null): string {
  return [
    "/**",
    " * Generated by backeneko. Rewritten on every start; do not edit.",
    " */",
    "",
    "declare namespace Backeneko {",
    PROXY,
    "",
    INTERCEPT,
    ...(schema ? ["", renderSchemaNamespace(schema)] : []),
    "}",
    "",
  ].join("\n");
}
