import {
  Kind,
  isTypeDefinitionNode,
  isTypeExtensionNode,
  parse,
  print,
  type DefinitionNode,
  type DocumentNode,
  type TypeDefinitionNode,
} from "graphql";
import type { SchemaSourceFile } from "./collect.ts";

export interface MergeResult {
  document: DocumentNode;
  errors: string[];
  skippedExecutables: string[];
}

function toExtension(def: TypeDefinitionNode): DefinitionNode {
  switch (def.kind) {
    case Kind.OBJECT_TYPE_DEFINITION:
      return { ...def, kind: Kind.OBJECT_TYPE_EXTENSION };
    case Kind.INTERFACE_TYPE_DEFINITION:
      return { ...def, kind: Kind.INTERFACE_TYPE_EXTENSION };
    case Kind.UNION_TYPE_DEFINITION:
      return { ...def, kind: Kind.UNION_TYPE_EXTENSION };
    case Kind.ENUM_TYPE_DEFINITION:
      return { ...def, kind: Kind.ENUM_TYPE_EXTENSION };
    case Kind.SCALAR_TYPE_DEFINITION:
      return { ...def, kind: Kind.SCALAR_TYPE_EXTENSION };
    default:
      return { ...def, kind: Kind.INPUT_OBJECT_TYPE_EXTENSION };
  }
}

function executableName(def: DefinitionNode): string {
  if (def.kind === Kind.OPERATION_DEFINITION) {
    return def.name ? `${def.operation} ${def.name.value}` : `${def.operation} <anonymous>`;
  }
  if (def.kind === Kind.FRAGMENT_DEFINITION) {
    return `fragment ${def.name.value}`;
  }
  return def.kind.toLowerCase().replace(/_/g, " ");
}

export function mergeSchemaDocuments(files: SchemaSourceFile[]): MergeResult {
  const rootDefinitions: DefinitionNode[] = [];
  const typeDefinitions = new Map<string, DefinitionNode>();
  const extensions: DefinitionNode[] = [];
  const directiveNames = new Set<string>();
  const skippedExecutables: string[] = [];
  const errors: string[] = [];
  let schemaDefinitionSeen = false;

  for (const file of files) {
    let document: DocumentNode;
    try {
      document = parse(file.content);
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      errors.push(`${file.relativePath}: ${message}`);
      continue;
    }

    for (const def of document.definitions) {
      if (def.kind === Kind.SCHEMA_DEFINITION || def.kind === Kind.SCHEMA_EXTENSION) {
        if (!schemaDefinitionSeen) {
          schemaDefinitionSeen = true;
          rootDefinitions.push(def);
        }
        continue;
      }
      if (def.kind === Kind.DIRECTIVE_DEFINITION) {
        if (!directiveNames.has(def.name.value)) {
          directiveNames.add(def.name.value);
          rootDefinitions.push(def);
        }
        continue;
      }
      if (def.kind === Kind.OPERATION_DEFINITION || def.kind === Kind.FRAGMENT_DEFINITION) {
        skippedExecutables.push(`${file.relativePath}: ${executableName(def)}`);
        continue;
      }
      if (isTypeExtensionNode(def)) {
        extensions.push(def);
        continue;
      }
      if (isTypeDefinitionNode(def)) {
        const name = def.name.value;
        if (typeDefinitions.has(name)) extensions.push(toExtension(def));
        else typeDefinitions.set(name, def);
        continue;
      }
    }
  }

  return {
    document: {
      kind: Kind.DOCUMENT,
      definitions: [...rootDefinitions, ...typeDefinitions.values(), ...extensions],
    },
    errors,
    skippedExecutables,
  };
}

export interface SkippedDefinition {
  name: string;
  reason: string;
}

export function renderSdl(
  document: DocumentNode,
  sources: string[],
  skipped: SkippedDefinition[] = [],
): string {
  const header = ["# Generated by backeneko — do not edit by hand.", "# Sources:"];
  for (const source of sources) header.push(`#   - ${source}`);
  if (skipped.length > 0) {
    header.push("#", "# Skipped definitions (errors in the source schema):");
    for (const entry of skipped) header.push(`#   - ${entry.name}: ${entry.reason}`);
  }
  header.push("", "");
  return header.join("\n") + print(document) + "\n";
}
